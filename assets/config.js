// Сетка точек погоды: шаг 1,5° по широте и 2° по долготе внутри контура РК + города
export function weatherPoints() {
  const pts = [];
  const inside = (lon, lat) => {
    let c = false;
    for (let i = 0, j = OUTLINE.length - 1; i < OUTLINE.length; j = i++) {
      const [xi, yi] = OUTLINE[i], [xj, yj] = OUTLINE[j];
      if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) c = !c;
    }
    return c;
  };
  for (let lat = 41; lat <= 55.5; lat += 1.5)
    for (let lon = 47; lon <= 87; lon += 2)
      if (inside(lon, lat)) pts.push({ id: `g${lat}_${lon}`, lat, lon, grid: true });
  for (const c of CITIES) pts.push({ id: c.id, lat: c.lat, lon: c.lon, name: c.name });
  return pts;
}
